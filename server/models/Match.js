import mongoose from 'mongoose';

const { Schema } = mongoose;

// One row per dorm member who played (guests are kept in config only).
const PlayerStat = new Schema({
  name: String,
  nameKey: { type: String, index: true }, // lowercased name, used to group a person across matches
  team: String,
  won: { type: Boolean, default: null },  // null = tie or not finished
  batting: {
    batted: Boolean, runs: Number, balls: Number, fours: Number, sixes: Number, dots: Number, out: Boolean,
    dismissal: { kind: String, bowler: String, fielder: String },
  },
  bowling: { balls: Number, oversEq: Number, runs: Number, wickets: Number, dots: Number, extras: Number },
  fielding: { catches: Number, runouts: Number, drops: Number },
}, { _id: false });

const Innings = new Schema({
  team: String, runs: Number, wickets: Number, overs: String, extras: Number, closed: Boolean,
}, { _id: false });

const MatchSchema = new Schema({
  // Source of truth: the setup + the ball-by-ball event log from the scorer.
  // Everything else below is derived from these two and rebuilt on every save.
  config: { type: Schema.Types.Mixed, required: true },
  events: { type: [Schema.Types.Mixed], default: [] },

  // Generated by the browser once per match so a retried save updates instead of duplicating.
  clientId: { type: String, unique: true, sparse: true },

  status: { type: String, enum: ['in_progress', 'completed'], default: 'in_progress', index: true },
  result: String,
  winner: String,
  teams: [String],
  innings: [Innings],
  superOvers: Schema.Types.Mixed,       // one entry per super over played after a tie (not counted in player stats)
  playerStats: [PlayerStat],
  facts: Schema.Types.Mixed,            // per-match numbers for the Home and 1v1 pages (see server/facts.js)
  factsVersion: { type: Number, index: true },
  abandoned: { type: Boolean, default: false }, // admin marked an unfinished match as abandoned (it leaves the Home page)

  playedAt: { type: Date, default: Date.now, index: true },
}, { timestamps: true });

export default mongoose.model('Match', MatchSchema);
